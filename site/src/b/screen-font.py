# Regenerates src/b/screen-font.js: Work Sans (wght 400-700) and Outfit (wght 500-700) subsets, printable ASCII + the few
# symbols the phone screens use, as base64 WOFF @font-face rules. They are embedded in the phone-screen SVG textures so
# their text renders in the page's fonts (an SVG loaded as an image cannot reach the page's fonts). Both fonts: SIL OFL 1.1.
# Run from site/: python3 src/b/screen-font.py
import base64, io, string
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
CHARS = string.printable.strip() + ' …•→←↑↓▶·“”‘’–—'
def face(path, family, lo, hi):
    f = instancer.instantiateVariableFont(TTFont(path), {'wght': (lo, hi)})
    o = subset.Options(); o.flavor = 'woff'; o.layout_features = ['kern', 'liga']; o.name_IDs = []; o.notdef_outline = True
    s = subset.Subsetter(o); s.populate(text=CHARS); s.subset(f)
    b = io.BytesIO(); f.flavor = 'woff'; f.save(b); print(family, len(b.getvalue()), 'bytes')
    return f"@font-face{{font-family:'{family}';font-weight:{lo} {hi};src:url(data:font/woff;base64,{base64.b64encode(b.getvalue()).decode()}) format('woff')}}"
css = face('assets/work-sans-variable.ttf', 'Work Sans', 400, 700) + face('assets/outfit-variable.ttf', 'Outfit', 500, 700)
open('src/b/screen-font.js', 'w').write(
  "// GENERATED by src/b/screen-font.py from assets/work-sans-variable.ttf + assets/outfit-variable.ttf (SIL OFL 1.1).\n"
  "// Subsets (ASCII + …•→←↑↓▶·“”‘’–—), embedded in the phone-screen SVG textures: an SVG image can't use the page's fonts.\n"
  f"export const SCREEN_FONT_CSS = \"{css}\";\n")
